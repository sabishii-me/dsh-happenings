// Builds the API bundle and the SQLite seed that ship inside the plugin package.
// The plugin must run without Wrangler, Workerd or a Cloudflare account.
import { build } from 'esbuild';
import { copyFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();

await build({
  entryPoints: [resolve(root, 'src/worker/index.ts')],
  outfile: resolve(root, 'plugin/lib/api.mjs'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  external: ['node:*'],
  banner: { js: '// Generated by scripts/build-plugin-api.mjs. Do not edit.' },
});

mkdirSync(resolve(root, 'plugin/data'), { recursive: true });
copyFileSync(resolve(root, 'migrations/0001_init.sql'), resolve(root, 'plugin/data/schema.sql'));
copyFileSync(resolve(root, 'migrations/0002_seed.sql'), resolve(root, 'plugin/data/seed.sql'));

console.log('built plugin/lib/api.mjs and plugin/data/*.sql');
